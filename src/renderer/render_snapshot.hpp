#pragma once
#include "utils/math.hpp"
#include "utils/offset_span.hpp"
#include "vertex.hpp"

namespace hammock::renderer {

    /// @struct BoundingBox
    /// Represent a box in space
    struct BoundingBox {
        math::Vec3 position;
        math::Vec3 size;
    };

    /// @struct RenderMesh
    /// indexes into master index buffer
    struct RenderMesh {
        std::uint32_t firstIndex;
        std::uint32_t indexCount;
    };

    /// @struct RenderMaterial
    /// indexes into material buffer
    struct RenderMaterial {
        std::uint32_t materialIndex;
    };

    /// @struct MeshDrawBatch
    /// Opaque/transparent mesh draws
    struct MeshDrawBatch {
        // Per-instance data (SoA)
        OffsetSpan<math::Mat4> worldTransforms;
        OffsetSpan<RenderMesh> meshes;
        OffsetSpan<RenderMaterial> materials;

        std::uint32_t count;

        // Sort key for state sorting (backend can sort this)
        OffsetSpan<uint64_t> sortKeys;  // pipeline | material | mesh | distance
    };

    /// @struct LightBatch
    struct LightBatch {
        OffsetSpan<math::Vec3> positions;
        OffsetSpan<math::Vec3> colors;
        OffsetSpan<float> intensities;
        OffsetSpan<float> radii;            // For point/spot
        OffsetSpan<math::Vec3> directions;  // For directional/spot
        OffsetSpan<float> innerConeAngles;  // For spot
        OffsetSpan<float> outerConeAngles;  // For spot

        std::uint32_t count;
    };

    /// @structDebugDrawBatch
    struct DebugDrawBatch {
        OffsetSpan<math::Vec3> lineStarts;
        OffsetSpan<math::Vec3> lineEnds;
        OffsetSpan<math::Vec3> lineColors;

        OffsetSpan<BoundingBox> boxes;
        OffsetSpan<math::Vec3> boxColors;

        std::uint32_t lineCount;
        std::uint32_t boxCount;
    };

    /// @struct ViewData
    /// camera related data
    struct ViewData {
        uint32_t width;
        uint32_t height;
        math::Mat4 view;
        math::Mat4 projection;
    };

    /// @struct UserInterfaceDrawBatch
    struct UserInterfaceDrawBatch {
        OffsetSpan<UiVertex> vertices;
    };

    /// @struct RenderPacket
    /// @brief Immutable data generated by the renderer frontend and consumed by the renderer backend
    struct RenderSnapshotHeader {
        // View data
        ViewData view;

        // Visible geometry (already culled)
        MeshDrawBatch opaqueDraws;
        MeshDrawBatch transparentDraws;

        // Lighting data
        LightBatch directionalLights;
        LightBatch pointLights;
        LightBatch spotLights;

        // Debug
        DebugDrawBatch debugDraws;

        // User Interface
        UserInterfaceDrawBatch uiDraws;

        // Frame metadata
        uint64_t frameNumber;
    };


}  // namespace hammock::renderer
